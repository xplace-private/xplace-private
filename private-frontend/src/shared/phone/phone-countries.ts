import {
  formatIncompletePhoneNumber,
  type CountryCode,
} from 'libphonenumber-js'

export interface PhoneCountry {
  code: CountryCode
  flag: string
  name: string
  phoneCode: string
}

export function filterPhoneCountries(
  countries: readonly PhoneCountry[],
  query: string,
): readonly PhoneCountry[] {
  const normalizedQuery = query.trim().toLowerCase()
  if (normalizedQuery === '') return countries

  return countries.filter((country) =>
    `${country.name} ${country.code} ${country.phoneCode}`
      .toLowerCase()
      .includes(normalizedQuery),
  ).sort(
    (left, right) =>
      Number(right.code.toLowerCase() === normalizedQuery) -
      Number(left.code.toLowerCase() === normalizedQuery),
  )
}

export function formatPhoneInput(
  country: PhoneCountry,
  value: string,
): string {
  return formatIncompletePhoneNumber(
    nationalDigits(country, value),
    country.code,
  ).replace(/\D+$/, '')
}

export function formatPhoneNumber(
  country: PhoneCountry,
  value: string,
): string {
  const digits = nationalDigits(country, value)
  const withoutTrunkPrefix =
    country.code === 'IT' || country.code === 'VA'
      ? digits
      : digits.replace(/^0/, '')

  return `${country.phoneCode}${withoutTrunkPrefix}`
}

function nationalDigits(country: PhoneCountry, value: string): string {
  const digits = value.replace(/\D/g, '')
  const callingDigits = country.phoneCode.slice(1)

  return value.trimStart().startsWith('+') && digits.startsWith(callingDigits)
    ? digits.slice(callingDigits.length)
    : digits
}

